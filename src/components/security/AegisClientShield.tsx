"use client";

import React, { useEffect, useRef } from "react";
import { usePathname } from "next/navigation";

export default function AegisClientShield() {
  const pathname = usePathname();
  const hasReportedRef = useRef(false);

  useEffect(() => {
    if (typeof window === "undefined") return;

    // 1. Detect Headless Browsers, Automation Frameworks & WebDrivers
    const isWebDriver = Boolean(navigator.webdriver);
    const win = window as any;
    const hasAutomationHooks = Boolean(
      win.__playwright ||
      win.__puppeteer_evaluation_script__ ||
      win._phantom ||
      win.callPhantom ||
      win.domAutomation ||
      win.domAutomationController ||
      (document as any).__selenium_unwrapped ||
      (document as any).__webdriver_script_fn
    );

    // If headless / automation environment detected and not yet reported
    if ((isWebDriver || hasAutomationHooks) && !hasReportedRef.current) {
      hasReportedRef.current = true;
      fetch("/api/security/sentinel", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          action: "report_telemetry",
          path: pathname,
          clientTelemetry: {
            isWebDriver,
            hasAutomationHooks,
          },
        }),
      }).catch(() => {});
    }

    // 2. Synthetic Click Burst Monitor (detects automated bot click scripts without human pointer entropy)
    let untrustedClicks = 0;
    const handleGlobalClick = (e: MouseEvent) => {
      // isTrusted is false when generated by synthetic event dispatchers (.click(), new MouseEvent())
      if (!e.isTrusted) {
        untrustedClicks++;
        if (untrustedClicks >= 3 && !hasReportedRef.current) {
          hasReportedRef.current = true;
          fetch("/api/security/sentinel", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              action: "report_telemetry",
              path: pathname,
              clientTelemetry: {
                untrustedClicks,
              },
            }),
          }).catch(() => {});
        }
      }
    };

    window.addEventListener("click", handleGlobalClick, { capture: true, passive: true });
    return () => {
      window.removeEventListener("click", handleGlobalClick, { capture: true });
    };
  }, [pathname]);

  // Handler for invisible DOM honeypot trap
  const handleHoneypotTriggered = () => {
    fetch("/api/security/sentinel", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        action: "report_telemetry",
        path: pathname,
        clientTelemetry: {
          honeypotTriggered: true,
        },
      }),
    }).catch(() => {});
  };

  return (
    <div
      aria-hidden="true"
      style={{
        position: "absolute",
        left: "-9999px",
        top: "-9999px",
        width: "1px",
        height: "1px",
        opacity: 0,
        pointerEvents: "none",
        zIndex: -1,
      }}
    >
      {/* Invisible DOM Honeypot Traps for AI Crawlers & Automated Scrapers */}
      <a
        href="#aegis-security-decoy-trap"
        tabIndex={-1}
        onClick={(e) => {
          e.preventDefault();
          handleHoneypotTriggered();
        }}
        rel="nofollow"
      >
        EdWorld Internal Telemetry Index
      </a>
      <input
        type="text"
        name="edworld_decoy_field"
        tabIndex={-1}
        autoComplete="off"
        onChange={handleHoneypotTriggered}
      />
    </div>
  );
}
